def probe(t):
    t = min(1.0, max(0.0, t))
    a = {}
    for m, j, c in COEF:
        a[m] = a.get(m, 0.0) + c * math.cos(j * math.pi * t)
    xs = [(i + 0.5) / N for i in range(N)]
    return [sum(am * math.cos(m * math.pi * x) for m, am in a.items()) for x in xs]


